  function sanitizeLayoutJsonRaw(raw) {
    if (raw == null || raw === '') return '';
    var s = String(raw);
    if (s.charCodeAt(0) === 0xfeff) s = s.slice(1);
    return s.trim();
  }

  function normalizePrefsShape(p) {
    if (!p || typeof p !== 'object') return p;
    if (!Array.isArray(p.hiddenSections)) p.hiddenSections = [];
    if (!Array.isArray(p.hiddenCharts)) p.hiddenCharts = [];
    // Append any sections missing from order (e.g. newly added sections)
    if (Array.isArray(p.order)) {
      for (var _ni = 0; _ni < ALL_SECTION_IDS.length; _ni++) {
        if (p.order.indexOf(ALL_SECTION_IDS[_ni]) === -1) {
          p.order.push(ALL_SECTION_IDS[_ni]);
        }
      }
    }
    if (Array.isArray(p.widgets)) {
      p.widgets = p.widgets.filter(function (w) {
        if (w.type === 'layout' && Array.isArray(w.nested) && w.nested.length === 0) return false;
        if (DEPRECATED_WIDGETS && DEPRECATED_WIDGETS.indexOf(w.id) !== -1) return false;
        return true;
      });
      // Append newly added sections not yet in widgets[] (config migration)
      var widgetIds = {};
      for (var _wi = 0; _wi < p.widgets.length; _wi++) {
        if (p.widgets[_wi].id) widgetIds[p.widgets[_wi].id] = true;
      }
      for (var _ai = 0; _ai < ALL_SECTION_IDS.length; _ai++) {
        var _sid = ALL_SECTION_IDS[_ai];
        if (!widgetIds[_sid] && p.hiddenSections.indexOf(_sid) === -1) {
          p.widgets.push({ id: _sid, span: 12 });
        }
      }
    }
    return p;
  }

  function prefsHasUsableWidgets(p) {
    return !!(p && Array.isArray(p.widgets) && p.widgets.length);
  }

  function tryAcceptPrefsPayload(p) {
    if (!p || typeof p !== 'object') return null;
    if (p.v != null && Number(p.v) === PREFS_VERSION) p.v = PREFS_VERSION;
    else if (
      p.v == null &&
      ((Array.isArray(p.widgets) && p.widgets.length) || (Array.isArray(p.order) && p.order.length))
    ) {
      p.v = PREFS_VERSION;
    }
    if (p.v !== PREFS_VERSION) return null;
    return normalizePrefsShape(p);
  }

