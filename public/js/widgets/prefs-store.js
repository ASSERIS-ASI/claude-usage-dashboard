  function resetPrefs() {
    var reg = global.__widgetRegistry;
    var savedTemplates = Array.isArray(_prefs?.templates)
      ? JSON.parse(JSON.stringify(_prefs.templates))
      : [];
    // "Reset to defaults" and the Template Builder must share one canonical
    // page scaffold. Otherwise reset only restores 12-column section shells
    // while "Load Default" restores the actual per-page rows and chart spans.
    var scaffoldWidgets = global.__templateBuilder?.buildDefaultWidgetsFromScaffold?.();
    var defWidgets = Array.isArray(scaffoldWidgets) && scaffoldWidgets.length
      ? JSON.parse(JSON.stringify(scaffoldWidgets))
      : [];
    if (!defWidgets.length && reg) {
      for (var s of reg.sections) {
        if (s.parentSection) continue;
        if (s.reorderable === false) continue;
        if (global.__navModel?.isSectionAvailable && !global.__navModel.isSectionAvailable(s.id)) continue;
        defWidgets.push({ id: s.id, span: 12 });
      }
    }
    _prefs = defaultPrefs();
    _prefs.widgets = defWidgets.length ? defWidgets : null;
    _prefs.templates = savedTemplates;
    _prefs.activeTemplate = '';
    _prefs.activeTemplates = {};
    savePrefs();
    location.reload();
  }

