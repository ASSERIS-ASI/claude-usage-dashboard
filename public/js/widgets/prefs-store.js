  function syncPrefsOrderFromWidgets() {
    if (!_prefs?.widgets?.length) return false;
    var ids = [];
    for (var wEnt of _prefs.widgets) {
      var wT = wEnt.type || 'section';
      if (wT === 'layout') continue;
      ids.push(wEnt.id);
    }
    var changed = false;
    if (!_prefs.order || _prefs.order?.length !== ids.length) changed = true;
    else {
      for (var c = 0; c < ids.length; c++) {
        if (_prefs.order[c] !== ids[c]) { changed = true; break; }
      }
    }
    if (changed) { _prefs.order = ids; return true; }
    return false;
  }

  function syncPrefsWidgetsFromDraggableOrder(orderedIds) {
    if (!_prefs?.widgets?.length) return false;
    var inDrag = {};
    for (var oId of orderedIds) inDrag[oId] = true;
    var before = _prefs.widgets;
    var extras = [];
    for (var bw of before) {
      if (!inDrag[bw.id]) extras.push({ id: bw.id, span: bw.span });
    }
    var newW = [];
    for (var oid of orderedIds) {
      var span = 12;
      for (var bw2 of before) {
        if (bw2.id === oid) { span = bw2.span; break; }
      }
      newW.push({ id: oid, span: span });
    }
    for (var ext of extras) {
      var extraId = ext.id;
      var afterDragged = null;
      var foundExtra = false;
      for (var bw3 of before) {
        if (bw3.id === extraId) { foundExtra = true; continue; }
        if (foundExtra && inDrag[bw3.id]) { afterDragged = bw3.id; break; }
      }
      var inserted = false;
      if (afterDragged) {
        for (var ni = 0; ni < newW.length; ni++) {
          if (newW[ni].id === afterDragged) { newW.splice(ni, 0, ext); inserted = true; break; }
        }
      }
      if (!inserted) newW.push(ext);
    }
    _prefs.widgets = newW;
    return true;
  }

  // ── Template persistence ───────────────────────────────────────────

  function stripDeprecatedWidgets(tpl) {
    if (!tpl.widgets) return tpl;
    tpl.widgets = tpl.widgets.filter(function (w) { return DEPRECATED_WIDGETS.indexOf(w.id) === -1; });
    return tpl;
  }

  function inferPageTemplateScope(tpl) {
    if (!tpl || tpl.builtin || tpl.surfaceId || !Array.isArray(tpl.widgets) || !tpl.widgets.length) return tpl;
    var nav = global.__navModel;
    if (!nav?.getSectionSurface) return tpl;
    var inferred = '';
    for (var i = 0; i < tpl.widgets.length; i++) {
      var ownerId = tpl.widgets[i].section || tpl.widgets[i].id;
      var surface = nav.getSectionSurface(ownerId);
      if (!surface) continue;
      if (inferred && inferred !== surface.id) return tpl; // genuine legacy whole-dashboard template
      inferred = surface.id;
    }
    if (!inferred) return tpl;
    tpl.scope = 'page';
    tpl.surfaceId = inferred;
    var page = String(inferred).replace(/[^a-z0-9]+/gi, '_').replace(/^_+|_+$/g, '').toLowerCase();
    tpl.widgets = tpl.widgets.map(function (widget) {
      if (widget.surfaceId && widget.pageWidgetId) return widget;
      var rawId = widget.id || widget.bid || 'widget';
      var local = String(rawId).replace(/[^a-z0-9]+/gi, '_').replace(/^_+|_+$/g, '').toLowerCase();
      return Object.assign({}, widget, {
        surfaceId: inferred,
        pageWidgetId: page + '_' + local
      });
    });
    return tpl;
  }

  function migrateTemplateV2toV3(tpl) {
    if (tpl.version >= 3) return tpl;
    var out = { name: tpl.name, builtin: tpl.builtin || false, version: 3, widgets: [] };
    if (tpl.sectionWidgets) out.sectionWidgets = tpl.sectionWidgets;
    if (tpl.hiddenCharts) out.hiddenCharts = tpl.hiddenCharts;
    var w = tpl.widgets || [];
    for (var wItem of w) {
      out.widgets.push({ id: wItem.id, span: wItem.span || 12, type: wItem.type || 'section' });
    }
    return stripDeprecatedWidgets(out);
  }

  function migrateTemplateV1toV2(tpl) {
    if (tpl.version === 2 || tpl.version >= 3) return tpl;
    var order = tpl.order?.length ? tpl.order : ALL_SECTION_IDS;
    var hidden = tpl.hiddenSections || [];
    var widgets = [];
    for (var oItem of order) {
      if (!hidden.includes(oItem)) widgets.push({ id: oItem, span: 12 });
    }
    for (var sid of ALL_SECTION_IDS) {
      if (!order.includes(sid) && !hidden.includes(sid)) widgets.push({ id: sid, span: 12 });
    }
    var outTpl = { name: tpl.name, builtin: tpl.builtin || false, version: 2, widgets: widgets };
    if (tpl.sectionWidgets && typeof tpl.sectionWidgets === 'object') outTpl.sectionWidgets = tpl.sectionWidgets;
    return outTpl;
  }

  function loadTemplates() {
    // Templates live in _prefs.templates (server is source of truth).
    // If _prefs was already loaded (the common path), use it directly.
    if (_prefs && Array.isArray(_prefs.templates) && _prefs.templates.length) {
      return _prefs.templates.map(stripDeprecatedWidgets).map(inferPageTemplateScope);
    }
    // Cold-load fallback: fetch /api/layout directly.
    try {
      var xhrT = new XMLHttpRequest();
      xhrT.open('GET', '/api/layout', false);
      xhrT.send();
      if (xhrT.status === 200 && xhrT.responseText) {
        var parsed = JSON.parse(xhrT.responseText);
        if (parsed && Array.isArray(parsed.templates) && parsed.templates.length) {
          return parsed.templates.map(stripDeprecatedWidgets).map(inferPageTemplateScope);
        }
      }
    } catch (error) { logErr(error); }
    return [];
  }

  function saveTemplates(list) {
    ensurePrefs().templates = list;
    savePrefs();
  }

  function getActiveTemplateName(surfaceId) {
    if (surfaceId && _prefs?.activeTemplates && typeof _prefs.activeTemplates === 'object') {
      return _prefs.activeTemplates[surfaceId] || '';
    }
    return _prefs?.activeTemplate || '';
  }

  function setActiveTemplateName(name, surfaceId) {
    var p = ensurePrefs();
    if (surfaceId) {
      if (!p.activeTemplates || typeof p.activeTemplates !== 'object') p.activeTemplates = {};
      if (name) p.activeTemplates[surfaceId] = name;
      else delete p.activeTemplates[surfaceId];
    } else {
      p.activeTemplate = name;
    }
    savePrefs();
  }

  function getAllTemplates() {
    return BUILTIN_TEMPLATES.concat(loadTemplates());
  }

